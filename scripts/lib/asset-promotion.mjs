/**
 * SHA-256 of a file, streamed.
 *
 * `readFile` on `.local-game-derived/unity-facts/customs-unity-facts.json` allocates a 460 MB
 * Buffer on a drvfs mount. The digest is identical either way; only the resident set differs.
 */
export async function sha256File(absolutePath) {
  const hash = createHash('sha256');
  const stream = createReadStream(absolutePath, { highWaterMark: 1024 * 1024 });
  for await (const chunk of stream) hash.update(chunk);
  return hash.digest('hex');
}

async function walkFiles(dir, prefix, out) {
  let entries;
  try {
    entries = await readdir(dir, { withFileTypes: true });
  } catch (error) {
    if (error?.code === 'ENOENT' || error?.code === 'ENOTDIR') return;
    throw error;
  }
  for (const entry of entries.sort((left, right) => (left.name < right.name ? -1 : 1))) {
    const relativePath = prefix === '' ? entry.name : `${prefix}/${entry.name}`;
    const absolutePath = join(dir, entry.name);
    if (entry.isDirectory()) {
      await walkFiles(absolutePath, relativePath, out);
    } else if (entry.isFile()) {
      out.push({ relativePath, absolutePath });
    }
  }
}

/**
 * Index the digests of every file under a set of subtrees, restricted to files whose SIZE appears
 * in `candidateSizes`.
 *
 * The size filter is not a heuristic and does not weaken the check: a build artifact can only be
 * BYTE-IDENTICAL to a local file of exactly the same length, so a local file whose size no dist
 * file shares cannot be the thing we are looking for. What it buys is that the 460 MB facts dump
 * and 284 MB of screenshots are never read at all on a normal build — the reason this sweep can
 * afford to cover roots the old verifier had to leave out.
 *
 * Pass `candidateSizes: null` to disable the filter and index everything.
 */
export async function collectSubtreeHashes(subtrees, { baseDir, candidateSizes = null } = {}) {
  const hashes = new Map();
  let filesIndexed = 0;
  let filesSeen = 0;
  let bytesRead = 0;
  const present = [];

  for (const subtree of subtrees) {
    const absoluteBase = resolve(baseDir, ...subtree.path.split('/'));
    let baseStat;
    try {
      baseStat = await stat(absoluteBase);
    } catch {
      continue;
    }
    present.push(subtree.id);
    const files = [];
    if (baseStat.isFile()) {
      files.push({ relativePath: '', absolutePath: absoluteBase });
    } else if (baseStat.isDirectory()) {
      await walkFiles(absoluteBase, '', files);
    } else {
      continue;
    }
    for (const file of files) {
      const repoRelative = file.relativePath === ''
        ? subtree.path
        : `${subtree.path}/${file.relativePath}`;
      // `filePattern` narrows a mixed directory; a file it does not name belongs to another tier.
      if (!matchesSubtree(subtree, repoRelative)) continue;
      filesSeen += 1;
      let size;
      try {
        size = (await stat(file.absolutePath)).size;
      } catch {
        continue;
      }
      if (candidateSizes !== null && !candidateSizes.has(size)) continue;
      let digest;
      try {
        digest = await sha256File(file.absolutePath);
      } catch {
        continue;
      }
      filesIndexed += 1;
      bytesRead += size;
      if (!hashes.has(digest)) hashes.set(digest, `${repoRelative} (${subtree.id})`);
    }
  }

  return { hashes, filesIndexed, filesSeen, bytesRead, present };
}

/** Read the promotion manifest. An absent file means "nothing promoted", which is safe. */
export async function readPromotionManifest(manifestPath = PROMOTION_MANIFEST_PATH) {
  let bytes;
  try {
    bytes = await readFile(manifestPath);
  } catch (error) {
    if (error?.code === 'ENOENT') return { present: false, value: null, parseError: null };
    throw error;
  }
  try {
    return { present: true, value: JSON.parse(bytes.toString('utf8')), parseError: null };
  } catch (error) {
    return { present: true, value: null, parseError: error?.message ?? String(error) };
  }
}

/**
 * Prove each validated entry against disk.
 *
 * Three independent hash bindings have to hold before an entry may clear anything:
 *
 *   1. every receipt document hashes to its declared value — so editing the factory or the catalog
 *      invalidates every promotion built from it, loudly, at the next build;
 *   2. the source file, when the local package is on this machine, hashes to the entry's `sha256`
 *      and matches its `bytes`;
 *   3. (in the verifier) the file actually sitting in `dist/` hashes to that same `sha256`.
 *
 * A clean checkout without the local packages fails (2) benignly: `sourcePresent: false` is
 * recorded and the entry still verifies, because (1) and (3) are the two that actually gate what
 * ships, and both hold without any local package on disk.
 */
export async function verifyPromotionEntries(entries, {
  repositoryRoot = REPOSITORY_ROOT,
  captureHashes = null,
} = {}) {
  const verified = new Map();
  const errors = [];
  const records = [];

  for (const entry of entries) {
    const failures = [];

    for (const document of entry.receipt.documents) {
      const absolute = resolve(repositoryRoot, ...document.repoPath.split('/'));
      if (repoRelativePosix(repositoryRoot, absolute) === null) {
        failures.push({
          code: 'ERR_PROMOTION_RECEIPT_PATH',
          path: `${entry.id}.receipt.${document.role}`,
          message: `${document.repoPath} escapes the repository root`,
        });
        continue;
      }
      let actual;
      try {
        actual = `sha256:${await sha256File(absolute)}`;
      } catch (error) {
        failures.push({
          code: 'ERR_PROMOTION_RECEIPT_MISSING',
          path: `${entry.id}.receipt.${document.role}`,
          message: `${document.repoPath} is unreadable (${error?.code ?? error})`,
        });
        continue;
      }
      if (actual !== document.sha256) {
        failures.push({
          code: 'ERR_PROMOTION_RECEIPT_HASH',
          path: `${entry.id}.receipt.${document.role}`,
          message: `${document.repoPath} declares ${document.sha256} but hashes to ${actual}`,
        });
      }
    }

    let sourcePresent = false;
    const sourceAbsolute = resolve(repositoryRoot, ...entry.sourceRepoPath.split('/'));
    let sourceStat = null;
    try {
      sourceStat = await stat(sourceAbsolute);
    } catch {
      sourceStat = null;
    }
    if (sourceStat?.isFile()) {
      sourcePresent = true;
      if (sourceStat.size !== entry.bytes) {
        failures.push({
          code: 'ERR_PROMOTION_SOURCE_BYTES',
          path: `${entry.id}.bytes`,
          message: `declares ${entry.bytes} bytes but ${entry.sourceRepoPath} contains ${sourceStat.size}`,
        });
      } else {
        const actual = `sha256:${await sha256File(sourceAbsolute)}`;
        if (actual !== entry.sha256) {
          failures.push({
            code: 'ERR_PROMOTION_SOURCE_HASH',
            path: `${entry.id}.sha256`,
            message: `declares ${entry.sha256} but ${entry.sourceRepoPath} hashes to ${actual}`,
          });
        }
      }
    }

    // Last belt on the capture rule, this time by CONTENT rather than by path: an entry whose
    // approved digest happens to be a capture's digest is refused outright.
    if (captureHashes) {
      const bare = entry.sha256.slice('sha256:'.length);
      const source = captureHashes.get(bare);
      if (source !== undefined) {
        failures.push({
          code: 'ERR_PROMOTION_CAPTURE',
          path: `${entry.id}.sha256`,
          message: `declares the digest of a raw capture (${source}); a capture is not promotable`,
        });
      }
    }

    records.push({
      id: entry.id,
      source: entry.source,
      sourceRepoPath: entry.sourceRepoPath,
      distPath: entry.distPath,
      sha256: entry.sha256,
      sourcePresent,
      verified: failures.length === 0,
    });
    if (failures.length === 0) {
      verified.set(entry.distPath, entry);
    } else {
      errors.push(...failures);
    }
  }

  return { verified, errors, records };
}
