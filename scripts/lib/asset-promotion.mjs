/** Normalize an absolute path to a repo-relative POSIX path, or null if it escapes the root. */
export function repoRelativePosix(rootDir, absolutePath) {
  const relation = relative(rootDir, absolutePath);
  if (relation === '' || relation === '..' || relation.startsWith(`..${sep}`) || relation.startsWith('../')) {
    return null;
  }
  return relation.split(sep).join('/');
}

function matchesSubtree(entry, repoRelative) {
  const base = entry.path;
  if (repoRelative !== base && !repoRelative.startsWith(`${base}/`)) return false;
  if (!entry.filePattern) return true;
  const rest = repoRelative === base ? '' : repoRelative.slice(base.length + 1);
  return rest !== '' && !rest.includes('/') && entry.filePattern.test(rest);
}

/** The capture entry covering `repoRelative`, or null. Tier `raw-capture` only. */
export function captureSubtreeFor(repoRelative) {
  return CAPTURE_SUBTREES.find((entry) => matchesSubtree(entry, repoRelative)) ?? null;
}

/** The intermediate entry covering `repoRelative`, or null. Tier `intermediate` only. */
export function intermediateSubtreeFor(repoRelative) {
  return INTERMEDIATE_SUBTREES.find((entry) => matchesSubtree(entry, repoRelative)) ?? null;
}

/**
 * The tier of any repo-relative path: `raw-capture`, `intermediate`, `promotable`, or `other`.
 * One function so the classification in the docs and the classification the build enforces cannot
 * drift apart.
 */
export function classifyLocalPath(repoRelative) {
  const capture = captureSubtreeFor(repoRelative);
  if (capture) return { tier: 'raw-capture', id: capture.id, why: capture.why };
  const intermediate = intermediateSubtreeFor(repoRelative);
  if (intermediate) return { tier: 'intermediate', id: intermediate.id, why: intermediate.why };
  for (const [key, source] of Object.entries(PROMOTABLE_SOURCES)) {
    if (!repoRelative.startsWith(`${source.root}/`)) continue;
    if (source.filePattern.test(repoRelative.slice(source.root.length + 1))) {
      return { tier: 'promotable', id: key, why: source.why };
    }
  }
  return { tier: 'other', id: null, why: null };
}

