// manifest validation — pure, no filesystem

class PromotionError extends Error {
  constructor(code, path, message) {
    super(path ? `${path}: ${message}` : message);
    this.name = 'PromotionError';
    this.code = code;
    this.path = path;
  }
}

function isPlainObject(value) {
  if (value === null || typeof value !== 'object' || Array.isArray(value)) return false;
  const prototype = Object.getPrototypeOf(value);
  return prototype === Object.prototype || prototype === null;
}

function exactKeys(value, required, optional, path, fail) {
  if (!isPlainObject(value)) fail('ERR_PROMOTION_SCHEMA', path, 'must be an object');
  for (const key of required) {
    if (!Object.prototype.hasOwnProperty.call(value, key)) {
      fail('ERR_PROMOTION_SCHEMA', path, `is missing required field ${key}`);
    }
  }
  const allowed = new Set([...required, ...optional]);
  const extra = Object.keys(value).filter((key) => !allowed.has(key));
  if (extra.length > 0) fail('ERR_PROMOTION_SCHEMA', path, `has unsupported field(s): ${extra.join(', ')}`);
  return value;
}

function safeRelative(value, path, fail) {
  if (typeof value !== 'string' || !SAFE_RELATIVE_PATH.test(value)) {
    fail('ERR_PROMOTION_PATH', path, 'must be a safe relative path');
  }
  if (value.split('/').some((segment) => segment === '' || segment === '.' || segment === '..')) {
    fail('ERR_PROMOTION_PATH', path, 'must not contain empty or traversal segments');
  }
  return value;
}

/**
 * Validate the manifest document against the closed registry. Pure: it decides shape, source-key
 * membership, path safety, capture containment and uniqueness. It never touches disk, so a test
 * can drive every refusal without a fixture.
 *
 * Returns `{ entries, errors }` rather than throwing: one malformed entry must not hide the rest,
 * and the build wants every reason at once.
 */
export function validatePromotionManifest(value, { path = 'asset-promotion-manifest.json' } = {}) {
  const errors = [];
  const fail = (code, at, message) => {
    throw new PromotionError(code, at, message);
  };
  const entries = [];

  let document;
  try {
    document = exactKeys(value, ['schemaVersion', 'documentType', 'promotions'], ['notes'], path, fail);
    if (document.schemaVersion !== PROMOTION_MANIFEST_SCHEMA_VERSION) {
      fail('ERR_PROMOTION_SCHEMA', `${path}.schemaVersion`, `must be ${PROMOTION_MANIFEST_SCHEMA_VERSION}`);
    }
    if (document.documentType !== PROMOTION_MANIFEST_DOCUMENT_TYPE) {
      fail('ERR_PROMOTION_SCHEMA', `${path}.documentType`, `must be ${PROMOTION_MANIFEST_DOCUMENT_TYPE}`);
    }
    if (!Array.isArray(document.promotions)) {
      fail('ERR_PROMOTION_SCHEMA', `${path}.promotions`, 'must be an array');
    }
    if (document.promotions.length > 20_000) {
      fail('ERR_PROMOTION_SCHEMA', `${path}.promotions`, 'must not hold more than 20000 entries');
    }
  } catch (error) {
    return { entries: [], errors: [{ code: error.code, path: error.path, message: error.message }] };
  }

  const seenIds = new Set();
  const seenDistPaths = new Set();

  document.promotions.forEach((raw, index) => {
    const at = `${path}.promotions[${index}]`;
    try {
      const entry = exactKeys(
        raw,
        ['id', 'source', 'sourcePath', 'distPath', 'sha256', 'bytes', 'approvedBy', 'approvedOn', 'receipt'],
        ['notes'],
        at,
        fail,
      );

      if (typeof entry.id !== 'string' || !ID_PATTERN.test(entry.id)) {
        fail('ERR_PROMOTION_SCHEMA', `${at}.id`, 'must be a portable stable id');
      }
      if (seenIds.has(entry.id)) fail('ERR_PROMOTION_DUPLICATE', `${at}.id`, `duplicates promotion id ${entry.id}`);
      seenIds.add(entry.id);

      // THE CLOSED ENUM. A capture root has no key here, so a capture is not merely unlisted —
      // there is no value of `source` that reaches one.
      const source = Object.prototype.hasOwnProperty.call(PROMOTABLE_SOURCES, entry.source)
        ? PROMOTABLE_SOURCES[entry.source]
        : null;
      if (source === null) {
        fail(
          'ERR_PROMOTION_UNKNOWN_SOURCE',
          `${at}.source`,
          `${JSON.stringify(entry.source)} is not a promotable source; the registry admits: `
            + `${Object.keys(PROMOTABLE_SOURCES).join(', ')}`,
        );
      }

      const sourcePath = safeRelative(entry.sourcePath, `${at}.sourcePath`, fail);
      if (!source.filePattern.test(sourcePath)) {
        fail(
          'ERR_PROMOTION_SOURCE_PATH',
          `${at}.sourcePath`,
          `${sourcePath} is not a file ${entry.source} may promote (${source.filePattern})`,
        );
      }
      const sourceRepoPath = `${source.root}/${sourcePath}`;
      // Belt to the enum's braces: even a registry key whose root were one day widened cannot
      // reach into a capture subtree.
      const capture = captureSubtreeFor(sourceRepoPath);
      if (capture) {
        fail(
          'ERR_PROMOTION_CAPTURE',
          `${at}.sourcePath`,
          `${sourceRepoPath} is a raw capture (${capture.id}) and is not promotable`,
        );
      }

      const distPath = safeRelative(entry.distPath, `${at}.distPath`, fail);
      if (!distPath.startsWith(PROMOTED_DIST_PREFIX)) {
        fail('ERR_PROMOTION_PATH', `${at}.distPath`, `must live under ${PROMOTED_DIST_PREFIX}`);
      }
      if (seenDistPaths.has(distPath)) {
        fail('ERR_PROMOTION_DUPLICATE', `${at}.distPath`, `duplicates dist path ${distPath}`);
      }
      seenDistPaths.add(distPath);

      if (typeof entry.sha256 !== 'string' || !SHA256_DECLARATION.test(entry.sha256)) {
        fail('ERR_PROMOTION_SCHEMA', `${at}.sha256`, 'must be a lowercase sha256:<64 hex> declaration');
      }
      if (!Number.isSafeInteger(entry.bytes) || entry.bytes < 1) {
        fail('ERR_PROMOTION_SCHEMA', `${at}.bytes`, 'must be a positive safe integer');
      }
      if (typeof entry.approvedBy !== 'string' || entry.approvedBy.length === 0 || entry.approvedBy.length > 120) {
        fail('ERR_PROMOTION_SCHEMA', `${at}.approvedBy`, 'must name who approved the promotion');
      }
      if (typeof entry.approvedOn !== 'string' || !DATE_PATTERN.test(entry.approvedOn)) {
        fail('ERR_PROMOTION_SCHEMA', `${at}.approvedOn`, 'must be an ISO YYYY-MM-DD date');
      }

      const receipt = exactKeys(entry.receipt, ['kind', 'documents'], [], `${at}.receipt`, fail);
      if (receipt.kind !== source.receipt.kind) {
        fail(
          'ERR_PROMOTION_RECEIPT_SHAPE',
          `${at}.receipt.kind`,
          `must be ${source.receipt.kind} for source ${entry.source}`,
        );
      }
      if (!Array.isArray(receipt.documents) || receipt.documents.length !== source.receipt.documents.length) {
        fail(
          'ERR_PROMOTION_RECEIPT_SHAPE',
          `${at}.receipt.documents`,
          `must declare exactly ${source.receipt.documents.length} document(s): `
            + `${source.receipt.documents.map((doc) => `${doc.role} (${doc.repoPath})`).join(', ')}`,
        );
      }
      const documents = receipt.documents.map((rawDocument, documentIndex) => {
        const documentAt = `${at}.receipt.documents[${documentIndex}]`;
        const declared = exactKeys(rawDocument, ['role', 'repoPath', 'sha256'], [], documentAt, fail);
        const required = source.receipt.documents[documentIndex];
        // Role AND repo path are pinned by the registry, in order. The manifest contributes the
        // hash and nothing else — which is precisely why editing a path in it promotes nothing.
        if (declared.role !== required.role || declared.repoPath !== required.repoPath) {
          fail(
            'ERR_PROMOTION_RECEIPT_SHAPE',
            documentAt,
            `must be role ${required.role} at ${required.repoPath}, not `
              + `${JSON.stringify(declared.role)} at ${JSON.stringify(declared.repoPath)}`,
          );
        }
        if (typeof declared.sha256 !== 'string' || !SHA256_DECLARATION.test(declared.sha256)) {
          fail('ERR_PROMOTION_SCHEMA', `${documentAt}.sha256`, 'must be a lowercase sha256:<64 hex> declaration');
        }
        return { role: declared.role, repoPath: declared.repoPath, sha256: declared.sha256 };
      });

      entries.push(Object.freeze({
        index,
        id: entry.id,
        source: entry.source,
        sourcePath,
        sourceRepoPath,
        distPath,
        sha256: entry.sha256,
        bytes: entry.bytes,
        approvedBy: entry.approvedBy,
        approvedOn: entry.approvedOn,
        receipt: Object.freeze({ kind: receipt.kind, documents: Object.freeze(documents) }),
        notes: entry.notes ?? null,
      }));
    } catch (error) {
      if (!(error instanceof PromotionError)) throw error;
      errors.push({ code: error.code, path: error.path, message: error.message });
    }
  });

  return { entries, errors };
}

