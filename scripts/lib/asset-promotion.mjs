// The promotion registry: what MAY leave a local package, and what may never.
//
// Background. `.local-game-derived/` and `.local-candidates/` used to be one undifferentiated
// "local" class, and `scripts/verify-build-boundary.mjs` enforced one rule about it: nothing from
// those roots may reach `dist/`. That rule was correct while nothing was ever meant to ship.
//
// The founder has since ruled that the packages contain no extracted game assets — "there are no
// real assets from the game in there. we took measurements and designed" — and approved promoting
// specific AUTHORED OUTPUTS to `public/`, shipped the way `public/assets/3d/customs/authored/
// fortress/` already ships. That ruling is supported by the artifacts: all 31 vegetation families
// report `geometryEvidence: "original approximation from scalar prototype identity and fallback
// envelope"`, generated by the committed factory `scripts/vegetation-asset-factory/
// vegetation_factory.py` from the git-tracked `prototype_catalog.json`.
//
// But the RAW CAPTURES never move, and the founder's ruling does not reach them. So the boundary
// splits into three tiers, and THIS FILE — not the manifest — is where a path's tier is decided:
//
//   * `PROMOTABLE_SOURCES` — a closed, code-level registry of the only subtrees a promotion
//     manifest entry may name. Each key fixes a root, a file-name pattern, and the exact set of
//     git-tracked provenance documents its receipt must cite, BY REPO PATH. The manifest supplies
//     hashes; it cannot supply paths.
//
//   * `CAPTURE_SUBTREES` (tier `raw-capture`) — genuine captures: the 460 MB scalar facts dump,
//     the raw Unity vegetation instance dumps, the sanitized scalar facts file, and the 65 in-game
//     photographs. A capture is not "unlisted", it is UNNAMEABLE: no `PROMOTABLE_SOURCES` key is
//     rooted at one, and `assertNotCapture()` rejects any entry whose resolved source path lands
//     inside one. On the dist side these get their own `capture` check that never consults the
//     manifest, so a capture in `dist/` fails whether or not somebody listed it.
//
//   * `INTERMEDIATE_SUBTREES` (tier `intermediate`) — build intermediates and QA artifacts: the
//     proof and probe packages, the review write-ups, the superseded v1 vegetation pack, the
//     candidates index. Not captures, but not promotable either, and no registry key names them.
//     They are indexed into the ordinary hash sweep so that copying one into `dist/` fails today,
//     which it does not before this change: `.local-candidates/survey-2026-09-01/` and the proof
//     packages were never under any scanned root, so a photograph renamed into `dist/assets/`
//     passed every check.
//
// Nothing here moves, copies, or deletes a file. It reads.
//
// ---------------------------------------------------------------------------
// WHAT THIS BOUNDARY DETECTS, AND WHAT IT DOES NOT (read before quoting it)
//
// It is a BYTE-IDENTITY boundary plus a set of path/name/content tripwires. Stated precisely:
//
//   DETECTED
//     * a raw capture copied into `dist/` unchanged, under any name, at any depth — matched by
//       sha256 against the committed capture-digest inventory, which is loaded whether or not the
//       `.local-*` roots exist on the build machine (this is the CI case: Vercel builds from a
//       clean checkout where those roots are absent);
//     * a capture package directory name, or an EFT screenshot file name, appearing in `dist/`;
//     * any local-package file copied into `dist/` unchanged, unless the promotion manifest names
//       that exact dist path with that exact digest and a receipt that verifies;
//     * an absolute EFT-install path or a local root name embedded in a build artifact, UTF-8 or
//       UTF-16LE — never clearable by a promotion;
//     * a symlink anywhere in `dist/`, and a symlink used as a promotion source or receipt;
//     * a promotion whose declared digest IS a capture's digest;
//     * an inventory that has gone stale against the capture roots present on this machine
//       (file count or size multiset drift), so "add a capture, skip the regenerate" fails here.
//
//   NOT DETECTED — and no heuristic in this repo pretends otherwise
//     * AUTHORSHIP. The verifier proves that bytes in `dist/` are or are not identical to bytes in
//       a known local file. It cannot prove who made those bytes or what they were derived from.
//       A promotion entry is an ASSERTION by the founder, recorded with a receipt; the receipt
//       proves the cited provenance documents have not changed since approval, not that they
//       generated the artifact.
//     * A TRANSFORMED OR RE-ENCODED CAPTURE. Re-save a screenshot as JPEG, resample a height
//       field, re-quantise a control map, wrap a capture in a container — the digest changes and
//       every hash check goes quiet. Nothing here does perceptual, structural or statistical
//       comparison, and building such a heuristic would trade a deterministic guarantee for a
//       guess. The control for this class is the CLOSED REGISTRY in `PROMOTABLE_SOURCES` plus
//       code review of the pipeline that writes `public/`, not the verifier.
//
// So the honest one-liner: this boundary makes an accidental or lazy leak impossible and a
// deliberate, transforming one no easier than it already was. Do not describe it as proof that
// nothing in `dist/` is game-derived.

